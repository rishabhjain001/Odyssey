"""BehaviorTrainer -- imagined actor-critic updates with zero environment steps.

This module provides :class:`BehaviorTrainer`, which trains the Actor and Critic
exclusively from imagined rollouts generated by the RSSM (Req 10.2, 10.6). No
real environment interaction occurs during behavior training; all training data
comes from :func:`~agent.behavior.imagine`.

Design:
    * The Actor is updated to maximise expected λ-returns (Actor objective:
      ``loss = -targets.mean()``). Gradients flow through ``targets`` into the
      Actor's action outputs and the RSSM prior, so targets are **not** detached
      for the actor loss.
    * The Critic is updated to regress the same λ-return targets via MSE.
      Targets are **detached** for the critic loss so that critic gradients do
      not propagate through the return computation into the actor (standard
      DreamerV2 practice).
    * Each component has its own Adam optimizer (separate updates, standard in
      DreamerV2) at a shared learning rate defaulting to 6e-4.
    * ``train_step`` records ``actor_loss`` and ``critic_loss`` per step into the
      MetricsStore via ``record_world_model_losses`` (reusing the existing
      general-purpose recording method rather than adding unnecessary API surface
      to MetricsStore) (Req 10.6).

References:
    - DreamerV2 (Hafner et al., 2020): imagined actor-critic with separate
      actor/critic optimizers and λ-return targets.
    - Dreamer (Hafner et al., 2019): λ-returns over imagined trajectories.
    - RSSM / PlaNet (Hafner et al., 2018): prior prediction for zero-env-step
      imagination.
    - Req 10.2: behavior training draws data exclusively from imagined rollouts.
    - Req 10.6: records actor objective and critic loss per step.
"""

from __future__ import annotations

import math
from typing import Optional

import torch
from torch import Tensor

from agent.behavior import Actor, Critic, imagine, lambda_returns
from agent.config import BehaviorConfig
from agent.heads import DiscountPredictor, RewardPredictor
from agent.rssm import RSSM
from agent.types import LatentState
from training.metrics import MetricsStore

__all__ = ["BehaviorTrainer"]

# Default learning rate for both Actor and Critic Adam optimizers.
# Matches DreamerV2 reference and aligns with WorldModelTrainer.
_DEFAULT_LR: float = 6e-4


class BehaviorTrainer:
    """Trains Actor and Critic exclusively from imagined RSSM rollouts.

    Both Actor and Critic have independent Adam optimizers so their gradients
    do not interfere.  A single call to :meth:`train_step` performs:

    1. Stack the provided starting :class:`~agent.types.LatentState` objects into
       a batch.
    2. Call :func:`~agent.behavior.imagine` to unroll the RSSM for
       ``config.imagination_horizon`` steps without touching the environment
       (Req 10.2).
    3. Compute Critic values over each rollout state plus a terminal bootstrap
       state to obtain a ``(H+1, B)`` value tensor.
    4. Compute λ-returns via :func:`~agent.behavior.lambda_returns` using
       ``config.lam``.  These are the training targets ``(H, B)``.
    5. Actor loss: ``-targets.mean()``  (actor maximises expected return).
       Targets are **not** detached so gradients flow into the actor.
    6. Critic loss: ``MSE(critic(state), targets.detach())`` averaged over all
       rollout states.
    7. Update Actor then Critic with their respective Adam optimizers.
    8. Record ``{"actor_loss": <float>, "critic_loss": <float>}`` in the metrics
       store (Req 10.6).

    Args:
        actor: The policy :class:`~agent.behavior.Actor` module.
        critic: The value :class:`~agent.behavior.Critic` module.
        rssm: The :class:`~agent.rssm.RSSM` used for imagined rollouts.
        reward_p: The :class:`~agent.heads.RewardPredictor` head.
        discount_p: The :class:`~agent.heads.DiscountPredictor` head.
        metrics_store: The central :class:`~training.metrics.MetricsStore` for
            recording per-step losses (Req 10.6).
        config: :class:`~agent.config.BehaviorConfig` with ``imagination_horizon``
            and ``lam`` settings.
        lr: Learning rate for both Adam optimizers (default 6e-4).
    """

    def __init__(
        self,
        actor: Actor,
        critic: Critic,
        rssm: RSSM,
        reward_p: RewardPredictor,
        discount_p: DiscountPredictor,
        metrics_store: MetricsStore,
        config: BehaviorConfig,
        lr: float = _DEFAULT_LR,
    ) -> None:
        self.actor = actor
        self.critic = critic
        self.rssm = rssm
        self.reward_p = reward_p
        self.discount_p = discount_p
        self.metrics_store = metrics_store
        self.config = config

        # Separate optimizers for Actor and Critic (standard DreamerV2 practice).
        self.actor_opt = torch.optim.Adam(actor.parameters(), lr=lr)
        self.critic_opt = torch.optim.Adam(critic.parameters(), lr=lr)

    # ------------------------------------------------------------------
    # Public training interface
    # ------------------------------------------------------------------

    def train_step(
        self,
        start_states: list[LatentState],
        step: int,
    ) -> Optional[dict[str, float]]:
        """Run one behavior-model training step on imagined rollouts (Req 10.2, 10.6).

        Args:
            start_states: One :class:`~agent.types.LatentState` per batch element.
                Each element should have ``deter`` of shape ``(1, deter_dim)``
                and ``stoch`` of shape ``(1, num_categoricals, num_classes)``; the
                batch dimension is combined here.  Alternatively, provide a list
                with a single pre-batched state.
            step: Current training step index, used for metrics recording.

        Returns:
            A dict ``{"actor_loss": float, "critic_loss": float}`` on success, or
            ``None`` if the step could not be completed (e.g. empty start_states
            or non-finite losses encountered).
        """
        if not start_states:
            return None

        # ------------------------------------------------------------------ #
        # 1. Combine starting states into a single batched LatentState.
        # ------------------------------------------------------------------ #
        start = _stack_latent_states(start_states)  # (B, ...)

        # ------------------------------------------------------------------ #
        # 2. Imagine H steps forward from the start state (Req 10.2, 10.1).
        #    No environment interaction takes place inside `imagine`.
        # ------------------------------------------------------------------ #
        horizon = self.config.imagination_horizon
        rollout = imagine(
            rssm=self.rssm,
            actor=self.actor,
            reward_p=self.reward_p,
            discount_p=self.discount_p,
            start=start,
            horizon=horizon,
        )
        # rollout.states: list of H LatentStates, each (B, ...)
        # rollout.rewards: (H, B)
        # rollout.discounts: (H, B)

        # ------------------------------------------------------------------ #
        # 3. Compute Critic values over the H rollout states plus the terminal
        #    bootstrap from the last rollout state → values shape (H+1, B).
        # ------------------------------------------------------------------ #
        # Values for states[0..H-1]:
        state_values: list[Tensor] = [
            self.critic(s) for s in rollout.states  # each (B,)
        ]
        # Terminal bootstrap: value of the final state (reused as V[H]).
        terminal_value = self.critic(rollout.states[-1])  # (B,)

        # Stack to (H+1, B): values[t] for t=0..H-1, then V[H] = terminal_value.
        values = torch.stack(state_values + [terminal_value], dim=0)  # (H+1, B)

        # ------------------------------------------------------------------ #
        # 4. Compute λ-returns (H, B) as training targets (Req 10.5).
        # ------------------------------------------------------------------ #
        targets = lambda_returns(
            rewards=rollout.rewards,    # (H, B)
            discounts=rollout.discounts,  # (H, B)
            values=values,              # (H+1, B)
            lam=self.config.lam,
        )  # (H, B)

        # ------------------------------------------------------------------ #
        # 5 & 6. Compute both losses before any optimizer.step() call.
        #
        # Actor loss: maximise expected return → loss = -targets.mean()
        #   Targets NOT detached; gradients flow through rollout into actor.
        #
        # Critic loss: MSE against detached targets (Req 10.5).
        #   Targets detached so critic gradients do not flow through returns.
        #   Critic values re-evaluated on the same rollout states (no new
        #   imagination needed; states are already computed).
        #
        # We zero both optimizers, compute both losses, backward both (actor
        # with retain_graph=True so the graph stays alive for the critic pass),
        # then step both.  Stepping after both backwards avoids in-place
        # parameter modifications invalidating the graph mid-computation.
        # ------------------------------------------------------------------ #
        self.actor_opt.zero_grad()
        self.critic_opt.zero_grad()

        # Actor loss (targets NOT detached).
        actor_loss = -targets.mean()

        # Critic values from the same rollout states, targets detached.
        targets_detached = targets.detach()  # (H, B)
        critic_values = torch.stack(
            [self.critic(s) for s in rollout.states], dim=0
        )  # (H, B)
        critic_loss = ((critic_values - targets_detached) ** 2).mean()

        # Backward: actor first with retain_graph because the graph nodes for
        # rollout.states are also needed by the critic backward.
        actor_loss.backward(retain_graph=True)
        critic_loss.backward()

        # Step both optimizers after all gradients are accumulated.
        self.actor_opt.step()
        self.critic_opt.step()

        # ------------------------------------------------------------------ #
        # 7. Record actor_loss and critic_loss per step (Req 10.6).
        #    Reuse record_world_model_losses to avoid unnecessary MetricsStore
        #    changes; keys "actor_loss" and "critic_loss" are self-documenting.
        # ------------------------------------------------------------------ #
        actor_loss_val = float(actor_loss.item())
        critic_loss_val = float(critic_loss.item())

        # Guard against non-finite values before recording.
        if not (math.isfinite(actor_loss_val) and math.isfinite(critic_loss_val)):
            return None

        self.metrics_store.record_world_model_losses(
            step,
            {
                "actor_loss": actor_loss_val,
                "critic_loss": critic_loss_val,
            },
        )

        return {"actor_loss": actor_loss_val, "critic_loss": critic_loss_val}


# ---------------------------------------------------------------------------
# Helper: stack a list of LatentStates into a single batched LatentState
# ---------------------------------------------------------------------------

def _stack_latent_states(states: list[LatentState]) -> LatentState:
    """Concatenate a list of LatentState objects along the batch dimension.

    Each state in ``states`` is expected to have ``deter`` of shape
    ``(B_i, deter_dim)`` and ``stoch`` of shape
    ``(B_i, num_categoricals, num_classes)``.  The returned state concatenates
    along dim 0, yielding shapes ``(sum(B_i), deter_dim)`` and
    ``(sum(B_i), num_categoricals, num_classes)``.

    Args:
        states: Non-empty list of :class:`~agent.types.LatentState` objects.

    Returns:
        A single :class:`~agent.types.LatentState` with the batch dimension
        equal to the sum of the individual batch sizes.
    """
    deter = torch.cat([s.deter for s in states], dim=0)
    stoch = torch.cat([s.stoch for s in states], dim=0)
    return LatentState(deter=deter, stoch=stoch)
